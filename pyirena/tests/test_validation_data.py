def test_unified_one_level_recovers_generating_parameters(manifest):
    from pyirena.core.unified import UnifiedFitModel
    meta = manifest["unified_one_level"]
    q, I, dI = _load(meta)
    m = UnifiedFitModel(1)
    lv = m.levels[0]
    lv.G = _truth(meta, "G") * 0.6
    lv.Rg = _truth(meta, "Rg") * 0.6
    lv.P = _truth(meta, "P") * 0.9
    lv.B = _truth(meta, "B") * 0.6
    lv.fit_G = lv.fit_Rg = lv.fit_B = lv.fit_P = True
    m.background = _truth(meta, "background") * 0.6
    m.fit(q, I, dI)
    assert lv.G == pytest.approx(_truth(meta, "G"), rel=0.03)
    assert lv.Rg == pytest.approx(_truth(meta, "Rg"), rel=0.02)
    assert lv.P == pytest.approx(_truth(meta, "P"), rel=0.02)
    assert lv.B == pytest.approx(_truth(meta, "B"), rel=0.10)


def test_size_distribution_recovers_volume_fraction_and_moments(manifest):
    from pyirena.core.sizes import SizesDistribution
    meta = manifest["sizes_sphere_lognormal"]
    q, I, dI = _load(meta)
    s = SizesDistribution()
    s.r_min, s.r_max, s.n_bins = 20.0, 320.0, 80
    s.log_spacing = False
    s.shape, s.contrast, s.method = "sphere", 100.0, "maxent"
    res = s.fit(q, I, dI)
    assert res["success"]
    r, p = np.asarray(res["r_grid"]), np.asarray(res["distribution"])
    vf = float(np.trapezoid(p, r))
    rms = float(np.sqrt(np.trapezoid(r ** 2 * p, r) / vf))
    assert vf == pytest.approx(_truth(meta, "volume_fraction"), rel=0.06)
    assert rms == pytest.approx(_truth(meta, "R_rms"), rel=0.06)


def test_simple_fits_recover_generating_parameters(manifest):
    from pyirena.core.simple_fits import SimpleFitModel
    for name, model, keys in (
        ("simple_guinier", "Guinier", ("I0", "Rg")),
        ("simple_porod", "Porod", ("Kp", "Background")),
        ("simple_sphere", "Sphere", ("Scale", "R")),
    ):
        meta = manifest[name]
        q, I, dI = _load(meta)
        m = SimpleFitModel()
        m.model = model
        for k in keys:
            m.params[k] = _truth(meta, k) * 0.6
        fixed = None
        if name == "simple_sphere":
            m.use_complex_bg = True
            m.params["BG_flat"] = _truth(meta, "BG_flat") * 0.6
            fixed = {"BG_B": 0.0, "BG_P": 4.0}
        res = m.fit(q, I, dI, fixed_params=fixed)
        assert res["success"], name
        for k in keys:
            assert res["params"][k] == pytest.approx(_truth(meta, k), rel=0.03), \
                f"{name}/{k}"


def test_waxs_peak_fit_recovers_generating_parameters(manifest):
    from pyirena.core import waxs_peakfit as W
    meta = manifest["waxs_three_gauss"]
    q, I, dI = _load(meta)
    bg = W.default_bg_params("Linear")
    for i, nm in enumerate(W.bg_param_names("Linear")):
        bg[nm]["value"] = _truth(meta, f"bg{i}") * 0.6
        bg[nm]["fit"] = True
    peaks = [W.default_peak_params("Gauss",
                                   Q0=_truth(meta, f"peak{i}_Q0") * 1.01,
                                   A=_truth(meta, f"peak{i}_A") * 0.6,
                                   FWHM=_truth(meta, f"peak{i}_FWHM") * 1.3)
             for i in (1, 2, 3)]
    res = W.WAXSPeakFitModel("Linear", peaks).fit(q, I, dI, bg, peaks)
    assert res["success"]
    for i, pk in enumerate(res["peaks"], 1):
        assert pk["Q0"]["value"] == pytest.approx(_truth(meta, f"peak{i}_Q0"), rel=0.005)
        assert pk["A"]["value"] == pytest.approx(_truth(meta, f"peak{i}_A"), rel=0.03)
        assert pk["FWHM"]["value"] == pytest.approx(_truth(meta, f"peak{i}_FWHM"), rel=0.03)


def test_data_manipulation_inverse_is_exact(manifest):
    from pyirena.core.data_manipulation import DataManipulation, ScaleConfig
    m_in, m_ref = manifest["manipulate_input"], manifest["manipulate_reference"]
    q, I, dI = _load(m_in)
    a, b = _truth(m_in, "a_multiply"), _truth(m_in, "b_add")
    res = DataManipulation.scale(q, I, dI, None, ScaleConfig(scale_I=1.0 / a,
                                                            background=b / a))
    _, I_ref, _ = _load(m_ref)
    assert _max_rel(res.I, I_ref) < 1e-12

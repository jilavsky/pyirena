def test_every_dataset_file_exists_and_loads(manifest):
    for meta in manifest.values():
        for key in ("ascii", "ascii_ideal", "nxcansas"):
            assert (VALIDATION_DIR / meta["files"][key]).exists(), meta["files"][key]
        q, I, dI = _load(meta)
        assert len(q) == meta["n_points"]
        assert np.all(q > 0) and np.all(I > 0) and np.all(dI > 0)
        assert np.all(np.diff(q) > 0)


def test_ideal_curve_stored_in_hdf5_matches_ascii(manifest):
    import h5py
    for meta in manifest.values():
        ascii_ideal = np.loadtxt(VALIDATION_DIR / meta["files"]["ascii_ideal"])
        with h5py.File(VALIDATION_DIR / meta["files"]["nxcansas"], "r") as f:
            stored = np.asarray(f["entry/ground_truth/I_ideal"][()], float)
        assert _max_rel(stored, ascii_ideal[:, 1]) < 1e-7


